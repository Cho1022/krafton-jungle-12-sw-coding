"""
[동적 프로그래밍 - 계단 오르기 (상향식 / Bottom-up)]

문제 설명:
- 상향식 DP로 계단을 오르는 방법의 수를 계산합니다.
- 한 번에 1칸 또는 2칸을 오를 수 있습니다.
- n번째 계단까지 오르는 경우의 수를 구합니다.

입력:
- n: 계단의 수

출력:
- n번째 계단까지 오르는 방법의 수

예제:
입력: n = 4
출력: 5
설명:
  1. 1+1+1+1
  2. 1+1+2
  3. 1+2+1
  4. 2+1+1
  5. 2+2

힌트:
- dp[i] = 계단 i까지 오르는 방법의 수
- dp[i] = dp[i-1] + dp[i-2]
- 작은 문제부터 차례로 계산

DP 문제 풀이 순서:
1. 부분 문제 정의: dp[i]가 무엇인지 정의
2. 점화식 도출: dp[i]를 이전 값으로 표현
3. 초기값 설정: dp[0], dp[1] 등
4. 계산 순서 결정: 상향식 or 하향식
5. 구현 및 검증
"""


def climb_stairs(n):
    """
    계단 오르기 (상향식 DP)

    Args:
        n: 계단의 수

    Returns:
        n번째 계단까지 오르는 방법의 수
    """
    # 만약 계단(n)이 1개나 2개라면?
    # -> 1개면 1 반환, 2개면 2 반환! (이게 초기 기초공사입니다)
    if n <= 2:
        return n
    # 1. dp 배열 준비하기
    # dp라는 리스트를 준비하는데, 크기는 (n+1)칸만큼 0으로 채워서 만든다. (인덱스를 계단 번호랑 맞추기 위해)
    # 예시를 들어서 해보자 10칸의 dp[10]를 만들고 싶으면 인덱스는 0부터 시작하니,

    dp = [0] * (n + 1)

    # 2. 기초공사 (초기값 설정)
    # dp[1] 은 ???
    # dp[2] 은 ???
    dp[1] = 1
    dp[2] = 2
    # 3. 바닥부터 지붕까지 벽돌 쌓기 (for문)
    # 3번 계단부터 n번 계단까지 차례대로 확인하면서:
    #     현재 계단(dp[i]) = ??? + ???

    # range(A , B + 1)이 기본 형태
    for i in range(3, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]
    # 최종적으로 dp[n]을 반환한다.
    return dp[n]

